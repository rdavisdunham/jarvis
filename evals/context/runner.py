@dataclass(frozen=True)
class Meeting:
    key: str
    envelope: SourceEnvelope
    received_at: datetime
    deleted_at: datetime | None
    segments: tuple[Segment, ...]  # transcript segments then private-note segments, with offsets

    @property
    def occurred_at(self) -> datetime:
        return self.envelope.occurred_at

    @property
    def zone(self) -> ZoneInfo:
        return ZoneInfo(self.envelope.timezone or "UTC")


@dataclass(frozen=True)
class History:
    name: str
    path: Path
    owner_id: str
    owner_actor: str
    actors: list[dict]
    meetings: list[Meeting]
    labels: dict

    def meeting(self, key: str) -> Meeting:
        return next(m for m in self.meetings if m.key == key)


def _paragraphs(text: str) -> list[str]:
    return [p.strip() for p in re.split(r"\n\s*\n", text) if p.strip()]


def source_segments(envelope: SourceEnvelope) -> list[Segment]:
    """The segments a revision stores: transcript segments (or text paragraphs), then private-note paragraphs
    attributed to the owner, with offsets into the newline-joined revision text."""
    if envelope.segments is not None:
        parts = [s.model_dump(exclude={"char_start", "char_end"}) for s in envelope.segments]
    else:
        parts = [{"seq": i, "text": p} for i, p in enumerate(_paragraphs(envelope.text))]
    next_seq = parts[-1]["seq"] + 1
    for i, note in enumerate(_paragraphs(envelope.private_notes or "")):
        parts.append({"seq": next_seq + i, "kind": "private_note", "attribution": "owner", "text": note})
    segments, offset = [], 0
    for part in parts:
        segments.append(Segment(**part, char_start=offset, char_end=offset + len(part["text"])))
        offset += len(part["text"]) + 1
    return segments


def load_history(path: str | Path) -> History:
    path = Path(path)
    manifest = json.loads((path / "manifest.json").read_text())
    meetings = []
    for entry in manifest["meetings"]:
        envelope = SourceEnvelope.model_validate_json((path / entry["file"]).read_text())
        if envelope.external_id != entry["key"]:
            raise ValueError(f"{entry['file']}: external_id {envelope.external_id!r} != key {entry['key']!r}")
        deleted = entry.get("deleted_at")
        meetings.append(Meeting(entry["key"], envelope, datetime.fromisoformat(entry["received_at"]),
                                datetime.fromisoformat(deleted) if deleted else None,
                                tuple(source_segments(envelope))))
    labels = json.loads((path / "labels.json").read_text())
    return History(manifest["history"], path, manifest["owner_id"], manifest["owner_actor"], manifest["actors"],
                   meetings, labels)


def fixture_id(history: str, *parts: str) -> str:
    return str(uuid5(ID_NAMESPACE, ":".join((history, *parts))))


def revision_id(history: History, meeting: Meeting) -> str:
    return fixture_id(history.name, "revision", meeting.key, "1")


# ---------------------------------------------------------------- the canonical export of a fixture


def _iso(value: datetime | None) -> str | None:
    return None if value is None else value.astimezone(ZoneInfo("UTC")).isoformat()


def build_export(history: History) -> dict:
    """The history's sources, revisions, segments, chunks, actor e-mail identities and owner state in the canonical
    export format, as they stand after every arrival and deletion. A deleted source keeps a content-free
    tombstone (source and revision rows without payload, segments or chunks), as the deletion job leaves it."""
    first = min(m.received_at for m in history.meetings)
    connections, sources, revisions, segments, chunks = [], [], [], [], []
    for connector in sorted({m.envelope.connector for m in history.meetings}):
        connections.append({"id": fixture_id(history.name, "connection", connector), "connector": connector,
                            "external_account": f"fixture:{history.name}:{connector}", "checkpoint": {},
                            "health": "ok", "last_error": None, "last_success_at": _iso(first), "enabled": True,
                            "created_at": _iso(first), "updated_at": _iso(first)})
    for meeting in sorted(history.meetings, key=lambda m: (m.envelope.connector, m.key)):
        env, deleted = meeting.envelope, meeting.deleted_at is not None
        source_id, rev_id = fixture_id(history.name, "source", meeting.key), revision_id(history, meeting)
        sources.append({
            "id": source_id, "connection_id": fixture_id(history.name, "connection", env.connector),
            "connector": env.connector, "external_id": env.external_id, "kind": "meeting", "title": env.title,
            "upstream_owner_email": env.upstream_owner_email, "upstream_owner_name": env.upstream_owner_name,
            "current_revision": 1, "status": "deleted" if deleted else "received",
            "availability": "deleted" if deleted else "available", "deleted_at": _iso(meeting.deleted_at),
            "created_at": _iso(meeting.received_at), "updated_at": _iso(meeting.deleted_at or meeting.received_at)})
        revisions.append({
            "id": rev_id, "source_id": source_id, "revision": 1,
            "content_hash": env.content_hash or content_hash(s.text for s in meeting.segments),
            "external_revision": env.external_revision, "change_kind": "content",
            "payload": {} if deleted else env.model_dump(mode="json", exclude_none=True),
            "occurred_at": _iso(env.occurred_at), "ended_at": _iso(env.ended_at), "timezone": env.timezone,
            "calendar_event_id": env.calendar_event_id, "upstream_updated_at": None,
            "participants": [] if deleted else [p.model_dump(mode="json", exclude_none=True) for p in env.participants],
            "summary": None if deleted else env.summary, "received_at": _iso(meeting.received_at),
            "created_at": _iso(meeting.received_at)})
        if deleted:
            continue
        for seg in meeting.segments:
            segments.append({
                "id": fixture_id(history.name, "segment", meeting.key, "1", str(seg.seq)), "revision_id": rev_id,
                "seq": seg.seq, "kind": seg.kind, "speaker_label": seg.speaker_label,
                "speaker_attribution": seg.attribution, "speaker_actor_id": None,
                "speaker_link_status": "unresolved", "speaker_provenance": {}, "text": seg.text,
                "start_ms": seg.start_ms, "end_ms": seg.end_ms, "char_start": seg.char_start,
                "char_end": seg.char_end, "created_at": _iso(meeting.received_at)})
        text = "\n".join(s.text for s in meeting.segments)
        chunks.append({
            "id": fixture_id(history.name, "chunk", meeting.key, "1", "0"), "revision_id": rev_id, "seq": 0,
            "segment_start": meeting.segments[0].seq, "segment_end": meeting.segments[-1].seq,
            "token_count": ceil(len(text) / 4), "text": text, "created_at": _iso(meeting.received_at),
            "updated_at": _iso(meeting.received_at)})
    identities = [
        {"id": fixture_id(history.name, "identity", actor["id"], email), "actor_id": actor["id"],
         "namespace": "email", "value": email, "normalized": email.lower(), "source_scope": None,
         "status": "confirmed", "provenance": {"origin": "fixture"}, "created_at": _iso(first),
         "updated_at": _iso(first)}
        for actor in history.actors for email in actor.get("emails", [])]
    identities.sort(key=lambda r: (r["actor_id"], r["namespace"], r["normalized"], r["id"]))
    empty = ("cursors", "runs", "decisions", "assertions", "assertion_versions", "evidence", "entity_links",
             "actor_merges", "proposals", "publications", "briefs")
    for row in (*connections, *sources, *revisions, *segments, *chunks, *identities):
        row["owner_id"] = history.owner_id
    return {
        "format": FORMAT, "version": VERSION, "owner_id": history.owner_id, "include_embeddings": False,
        "actors": [{"id": a["id"], "name": a["name"], "kind": a.get("kind", "person")}
                   for a in sorted(history.actors, key=lambda a: a["id"])],
        "owner_state": {"owner_id": history.owner_id, "epoch": 0, "decision_seq": 0, "paused": False,
                        "paused_at": None, "settings": {}, "created_at": _iso(first), "updated_at": _iso(first)},
        "connections": connections, "sources": sorted(sources, key=lambda r: (r["connector"], r["external_id"])),
        "revisions": sorted(revisions, key=lambda r: (r["source_id"], r["revision"], r["id"])),
        "segments": sorted(segments, key=lambda r: (r["revision_id"], r["seq"])),
        "chunks": sorted(chunks, key=lambda r: (r["revision_id"], r["seq"])),
        "actor_identities": identities, **{name: [] for name in empty},
    }


