# ---------------------------------------------------------------- engines


def _body_key(body: dict) -> str:
    return hashlib.sha256(json.dumps(body, sort_keys=True).encode()).hexdigest()


class ReplayExtractor:
    """The native extractor (package B3) with its model calls answered from `<history>/recorded/native/`.
    Each recording is `<sha256 of the request body>.json`. With `record=True` the real call is made (paid, needs
    a configured environment) and saved."""

    def __init__(self, module, recordings: Path, *, record: bool = False):
        self.module, self.recordings, self.record = module, recordings, record
        self.inner = module.NativeExtractor()

    @contextmanager
    def _patched(self):
        original = self.module.call_model

        def replay(owner, body, *args, **kwargs):
            path = self.recordings / f"{_body_key(body)}.json"
            if path.exists():
                return json.loads(path.read_text())
            if not self.record:
                raise EngineUnavailable(f"no recorded response {path.name}; rerun with --record")
            response = original(owner, body, *args, **kwargs)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(json.dumps(response, indent=1, sort_keys=True) + "\n")
            return response

        self.module.call_model = replay
        try:
            yield
        finally:
            self.module.call_model = original

    def extract(self, request: ExtractRequest):
        with self._patched():
            return self.inner.extract(request)


def make_engines(engine: str, history: History, *, record: bool = False) -> tuple[Extractor, Reconciler]:
    """`doubles`: rule-based extractor (or canned results from `recorded/doubles/<content_hash>.json`) and the
    keyed reconciler double. `native`: B3's extractor replaying recorded responses, with B5's reconciler when it
    is merged (expected as `jarvis.context.native.reconcile.NativeReconciler`), else the reconciler double."""
    if engine == "doubles":
        canned = history.path / "recorded" / "doubles"
        return (DoubleExtractor.from_directory(canned) if canned.is_dir() else DoubleExtractor()), DoubleReconciler()
    if engine != "native":
        raise ValueError(f"unknown engine {engine!r}; choose one of {ENGINES}")
    try:
        from jarvis.context.native import extract as native_extract
    except ImportError as error:
        raise EngineUnavailable("the native extractor (jarvis.context.native.extract, package B3) is not merged") \
            from error
    recordings = history.path / "recorded" / "native"
    if not record and not recordings.is_dir():
        raise EngineUnavailable(f"no recorded model responses in {recordings}")
    try:
        from jarvis.context.native.reconcile import NativeReconciler
        reconciler: Reconciler = NativeReconciler()
    except ImportError:
        reconciler = DoubleReconciler()
    return ReplayExtractor(native_extract, recordings, record=record), reconciler


# ---------------------------------------------------------------- in-memory application of engine results


@dataclass
class Entry:
    view: AssertionView
    meeting: str  # where it was first extracted
    evidence: list[tuple[str, EvidenceRef]]  # (meeting key, reference); shrinks when a source is deleted
    superseded_by: str | None = None


@dataclass
class Store:
    owner_id: str
    entries: dict[str, Entry] = field(default_factory=dict)
    counter: int = 0
    ops: Counter = field(default_factory=Counter)
    problems: list[str] = field(default_factory=list)
    rejected: int = 0
    stale_ops: int = 0
    segments: int = 0
    covered: int = 0

    def views(self, lifecycles=("current", "contested")) -> list[AssertionView]:
        return [e.view for e in self.entries.values() if e.view.lifecycle in lifecycles]

    def update(self, entry: Entry, **changes) -> None:
        entry.view = entry.view.model_copy(update={**changes, "revision": entry.view.revision + 1})


def _span_key(item: tuple[str, EvidenceRef]) -> tuple:
    meeting, ref = item
    return meeting, ref.segment_seq, ref.char_start, ref.char_end, ref.role


def _candidates(history: History) -> list[EntityCandidate]:
    return [EntityCandidate(ref=EntityRef(entity_type="actor", entity_id=a["id"]), name=a["name"],
                            aliases=[a["name"].split()[0]],
                            detail=", ".join(x for x in (a.get("role"), a.get("organization")) if x))
            for a in history.actors]


def receive(store: Store, history: History, meeting: Meeting, at: datetime, extractor: Extractor,
            reconciler: Reconciler) -> None:
    rev = revision_id(history, meeting)
    request = ExtractRequest(owner_id=history.owner_id, source_revision_id=rev, occurred_at=meeting.occurred_at,
                             timezone=meeting.envelope.timezone, title=meeting.envelope.title,
                             participants=meeting.envelope.participants, segments=list(meeting.segments),
                             candidates=_candidates(history))
    result = extractor.extract(request)
    store.problems += [f"{meeting.key}: {p}" for p in check_extraction(request, result)]
    texts = {s.seq: s.text for s in meeting.segments}
    store.segments += len(texts)
    store.covered += len(set(result.coverage) & set(texts))
    new = []
    for candidate in result.assertions:
        if not all(e.segment_seq in texts and e.matches(texts[e.segment_seq]) for e in candidate.evidence):
            store.rejected += 1  # core refuses inexact evidence
            continue
        store.counter += 1
        evidence = [e.model_copy(update={"source_revision_id": rev}) for e in candidate.evidence]
        view = AssertionView.model_validate({
            **candidate.model_dump(), "id": f"asr-{store.counter:04d}", "revision": 1, "lifecycle": "current",
            "valid_from": candidate.effective_from(meeting.occurred_at).model_dump(), "recorded_at": at,
            "source_revision_id": rev, "evidence": [e.model_dump() for e in evidence]})
        store.entries[view.id] = Entry(view, meeting.key, [(meeting.key, e) for e in evidence])
        new.append(view)
    if new:
        fresh = {v.id for v in new}
        ops = reconciler.reconcile(ReconcileRequest(owner_id=history.owner_id, changed=new,
                                                    related=[v for v in store.views() if v.id not in fresh]))
        for op in ops:
            apply_op(store, op)


def apply_op(store: Store, op: ReconcileOp) -> None:
    entries = [store.entries.get(t) for t in op.targets]
    if any(e is None for e in entries) or any(
            op.target_revisions.get(e.view.id, e.view.revision) != e.view.revision for e in entries):
        store.stale_ops += 1
        return
    store.ops[op.op] += 1
    if op.op == "equivalent":
        survivor, others = entries[0], entries[1:]
        seen = {_span_key(x) for x in survivor.evidence}
        merged = survivor.evidence + [x for o in others for x in o.evidence if _span_key(x) not in seen]
        earliest = min((e.view.valid_from for e in entries), key=lambda t: t.at)
        for other in others:
            del store.entries[other.view.id]
            for entry in store.entries.values():
                if entry.superseded_by == other.view.id:
                    entry.superseded_by = survivor.view.id
            if other.superseded_by and survivor.superseded_by is None:
                survivor.superseded_by = other.superseded_by
        survivor.evidence = merged
        store.update(survivor, valid_from=earliest)
    elif op.op == "conflict":
        for entry in entries:
            store.update(entry, lifecycle="contested")
    elif op.op == "supersede":
        old, new = entries
        valid_to = old.view.valid_to
        if valid_to is None or new.view.valid_from.at < valid_to.at:
            valid_to = new.view.valid_from
        old.superseded_by = new.view.id
        store.update(old, lifecycle="superseded", valid_to=valid_to)


def delete(store: Store, meeting: Meeting) -> None:
    """Remove the meeting's evidence; an assertion left without support is retracted, and a predecessor it had
    superseded becomes current again."""
    retracted = []
    for entry in store.entries.values():
        kept = [x for x in entry.evidence if x[0] != meeting.key]
        if len(kept) == len(entry.evidence):
            continue
        entry.evidence = kept
        if entry.view.lifecycle != "retracted" and not any(ref.role == "support" for _, ref in kept):
            store.update(entry, lifecycle="retracted")
            retracted.append(entry.view.id)
    for entry in store.entries.values():
        if entry.superseded_by in retracted and entry.view.lifecycle == "superseded":
            entry.superseded_by = None
            store.update(entry, lifecycle="current", valid_to=None)


def schedule(history: History, order: str, seed: int) -> list[tuple[str, Meeting, datetime]]:
    """(event, meeting, time) in processing order. Arrival order interleaves deletions at their times; the other
    orders process every arrival first, in the given order, at the recorded arrival times, then the deletions."""
    if order not in ORDERS:
        raise ValueError(f"unknown order {order!r}; choose one of {ORDERS}")
    deletions = sorted((m for m in history.meetings if m.deleted_at), key=lambda m: (m.deleted_at, m.key))
    if order == "arrival":
        events = [("receive", m, m.received_at) for m in history.meetings]
        events += [("delete", m, m.deleted_at) for m in deletions]
        return sorted(events, key=lambda e: (e[2], e[0] == "delete", e[1].key))
    meetings = sorted(history.meetings, key=lambda m: (m.occurred_at, m.key))
    if order == "shuffled":
        random.Random(seed).shuffle(meetings)
    slots = sorted(m.received_at for m in history.meetings)
    return [("receive", m, at) for m, at in zip(meetings, slots, strict=True)] + [
        ("delete", m, m.deleted_at) for m in deletions]


def simulate(history: History, extractor: Extractor, reconciler: Reconciler, events) -> Store:
    store = Store(history.owner_id)
    for event, meeting, at in events:
        if event == "receive":
            receive(store, history, meeting, at, extractor, reconciler)
        else:
            delete(store, meeting)
    return store


def redeliver(store: Store, history: History, extractor: Extractor, reconciler: Reconciler, events) -> None:
    """Deliver every surviving meeting again, forcing re-extraction (as a retry without stored stage results)."""
    deleted = {m.key for m in history.meetings if m.deleted_at}
    later = max(at for _, _, at in events) + timedelta(days=1)
    for i, (event, meeting, _) in enumerate(events):
        if event == "receive" and meeting.key not in deleted:
            receive(store, history, meeting, later + timedelta(minutes=i), extractor, reconciler)


def _normalized(text: str) -> str:
    return " ".join(WORD.findall(text.lower()))


def signature(store: Store, *, ids: bool = False) -> list:
    rows = []
    for entry in store.entries.values():
        v = entry.view
        row = [v.kind, _normalized(v.statement), v.modality, v.lifecycle, _iso(v.valid_from.at),
               _iso(v.valid_to.at) if v.valid_to else None, _iso(v.due.at) if v.due else None,
               sorted(list(_span_key(x)) for x in entry.evidence)]
        if ids:
            row = [v.id, v.revision, entry.superseded_by, *row]
        rows.append(row)
    return sorted(rows, key=json.dumps)


def supersessions(store: Store) -> set[tuple[str, str]]:
    return {(_normalized(e.view.statement), _normalized(store.entries[e.superseded_by].view.statement))
            for e in store.entries.values() if e.superseded_by and e.superseded_by in store.entries}


# ---------------------------------------------------------------- scoring


def _tokens(text: str) -> set[str]:
    return set(WORD.findall(text.lower()))


def _locate(history: History, meeting_key: str, quote: str) -> tuple[str, int, int, int]:
    hits = [(s.seq, s.text.index(quote)) for s in history.meeting(meeting_key).segments if quote in s.text]
    if len(hits) != 1:
        raise ValueError(f"label quote must occur in exactly one segment of {meeting_key}: {quote!r}")
    seq, start = hits[0]
    return meeting_key, seq, start, start + len(quote)


def _overlap(a: tuple, b: tuple) -> float:
    if a[:2] != b[:2]:
        return 0.0
    inter = min(a[3], b[3]) - max(a[2], b[2])
    return max(inter, 0) / max(min(a[3] - a[2], b[3] - b[2]), 1)


class Scorer:
    def __init__(self, history: History, store: Store):
        self.history, self.store = history, store
        self.spans = {label["id"]: [_locate(history, e["meeting"], e["quote"]) for e in label["evidence"]]
                      for label in history.labels["assertions"]}
        self.labels = {label["id"]: label for label in history.labels["assertions"]}
        self.entries = [e for e in store.entries.values()
                        if e.view.lifecycle in SCORED and e.view.modality == "asserted"]

    def matches(self, label: dict, entry: Entry) -> bool:
        if label["kind"] != entry.view.kind:
            return False
        spans = [(m, r.segment_seq, r.char_start, r.char_end) for m, r in entry.evidence]
        if any(_overlap(a, b) >= EVIDENCE_OVERLAP for a in self.spans[label["id"]] for b in spans):
            return True
        a, b = _tokens(label["statement"]), _tokens(entry.view.statement)
        return bool(a | b) and len(a & b) / len(a | b) >= STATEMENT_SIMILARITY

    def labelled(self, entry: Entry, labels) -> list[str]:
        return [label["id"] for label in labels if self.matches(label, entry)]

    def score(self, verified_only: bool) -> dict:
        def counted(item):
            return item["verified"] or not verified_only

        positives = [x for x in self.labels.values() if counted(x) and not x["from_deleted_source"]]
        unknown = [x for x in self.labels.values() if x not in positives]
        per_kind = {}
        for kind in ASSERTION_KINDS:
            labels = [x for x in positives if x["kind"] == kind]
            entries = [e for e in self.entries if e.view.kind == kind]
            tp = [e for e in entries if self.labelled(e, labels)]
            ignored = [e for e in entries if e not in tp and self.labelled(e, [x for x in unknown if x["kind"] == kind])]
            fp = len(entries) - len(tp) - len(ignored)
            found = [x for x in labels if any(self.matches(x, e) for e in entries)]
            if labels or entries:
                per_kind[kind] = {"labels": len(labels), "candidates": len(entries), "true_positive": len(tp),
                                  "false_positive": fp, "ignored": len(ignored), "found": len(found),
                                  "precision": _ratio(len(tp), len(tp) + fp), "recall": _ratio(len(found), len(labels))}
        return {"per_kind": per_kind, "commitments": self._commitments(positives),
                "must_not": self._must_not([x for x in self.history.labels["must_not"] if counted(x)]),
                "deletion_leaks": self._leaks(), "as_of": self._as_of([x for x in self.history.labels["as_of"] if counted(x)]),
                "open_loops": self._open_loops([x for x in self.history.labels["open_loops"] if counted(x)]),
                "supersession": self._supersession([x for x in self.history.labels["changes"] if counted(x)])}

    def _attributed(self, entry: Entry) -> str | None:
        """The actor the engine named as responsible: an entity ID, or a mention naming exactly one actor."""
        if not entry.view.responsible:
            return None
        ref = entry.view.responsible[0]
        if ref.entity_id:
            return ref.entity_id
        mention = (ref.mention or "").lower()
        named = [a["id"] for a in self.history.actors
                 if mention in (a["name"].lower(), a["name"].split()[0].lower())]
        return named[0] if len(named) == 1 else None

    def _commitments(self, positives) -> dict:
        due = Counter()
        attribution = Counter()
        for label in (x for x in positives if x["kind"] == "commitment"):
            meeting = self.history.meeting(label["meeting"])
            for entry in (e for e in self.entries if self.matches(label, e)):
                got = entry.view.due.at.astimezone(meeting.zone).date().isoformat() if entry.view.due else None
                due["correct" if got == label["due"] else "wrong"] += 1
                actor = self._attributed(entry)
                attribution["unresolved" if actor is None else
                            "correct" if actor in label["responsible"] else "wrong"] += 1
        return {"due_date": dict(due), "due_date_accuracy": _ratio(due["correct"], sum(due.values())),
                "attribution": dict(attribution), "attribution_errors": attribution["wrong"]}

    def _must_not(self, labels) -> dict:
        violations = []
        for label in labels:
            span = _locate(self.history, label["meeting"], label["quote"])
            for entry in self.entries:
                if entry.view.kind == label["kind"] and any(
                        _overlap(span, (m, r.segment_seq, r.char_start, r.char_end)) >= EVIDENCE_OVERLAP
                        for m, r in entry.evidence):
                    violations.append({"label": label["id"], "reason": label["reason"], "statement": entry.view.statement})
        return {"labels": len(labels), "violations": violations}

    def _leaks(self) -> list[str]:
        deleted = {m.key for m in self.history.meetings if m.deleted_at}
        return sorted(e.view.statement for e in self.entries if any(m in deleted for m, _ in e.evidence))

    def _as_of(self, questions) -> dict:
        corpus = [Indexed(owner_id=self.store.owner_id, text=e.view.statement, hit=Hit(
            ref_type="assertion", id=e.view.id, revision=e.view.revision, score=0, kind=e.view.kind,
            lifecycle=e.view.lifecycle, valid_from=e.view.valid_from.at,
            valid_to=e.view.valid_to.at if e.view.valid_to else None)) for e in self.entries]
        retriever, by_id = DoubleRetriever(corpus), {e.view.id: e for e in self.entries}
        results, outcome = [], Counter()
        for q in questions:
            scope = ScopePredicate(owner_id=self.store.owner_id, include_superseded=True,
                                   valid_at=datetime.fromisoformat(q["valid_at"]), kinds=q["kinds"])
            hits = retriever.retrieve(RetrieveQuery(text=q["question"], scope=scope, limit=1))
            family = [self.labels[x] for x in q["family"]]
            answer = self.labelled(by_id[hits[0].id], family) if hits else []
            verdict = "correct" if q["expected"] in answer else "stale" if answer else "unanswered"
            outcome[verdict] += 1
            results.append({"id": q["id"], "verdict": verdict,
                            "answer": by_id[hits[0].id].view.statement if hits else None})
        return {"questions": len(questions), **{k: outcome[k] for k in ("correct", "stale", "unanswered")},
                "stale_answer_rate": _ratio(outcome["stale"], len(questions)), "results": results}

    def _open_loops(self, loops) -> dict:
        commitments = [x for x in self.labels.values() if x["kind"] == "commitment"]
        results = []
        for loop in loops:
            at = datetime.fromisoformat(loop["as_of"])
            open_entries = [e for e in self.entries if e.view.kind == "commitment" and e.view.valid_from.at <= at
                            and (e.view.valid_to is None or at < e.view.valid_to.at)]
            predicted, unmatched = set(), 0
            for entry in open_entries:
                ids = self.labelled(entry, commitments)
                predicted |= set(ids)
                unmatched += not ids
            expected = set(loop["expected"])
            hit = len(predicted & expected)
            results.append({"id": loop["id"], "expected": sorted(expected), "predicted": sorted(predicted),
                            "unlabelled_open": unmatched,
                            "precision": _ratio(hit, len(predicted) + unmatched), "recall": _ratio(hit, len(expected))})
        return {"dates": len(loops), "results": results}

    def _supersession(self, changes) -> dict:
        agreed, errors = 0, []
        for change in changes:
            old = [e for e in self.entries if self.matches(self.labels[change["from"]], e)]
            new = {e.view.id for e in self.entries if self.matches(self.labels[change["to"]], e)}
            if any(e.superseded_by in new for e in old):
                agreed += 1
            else:
                errors.append({"change": change["id"], "found_old": bool(old), "found_new": bool(new)})
        return {"expected": len(changes), "agreed": agreed, "errors": errors}


def _ratio(numerator: int, denominator: int) -> float | None:
    return None if denominator == 0 else round(numerator / denominator, 4)


